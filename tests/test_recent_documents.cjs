const assert = require('node:assert/strict');
const R = require('../app/static/recent-documents.js');
const state = new Map();
const storage = {getItem: key => state.get(key), setItem: (key, value) => state.set(key, value), removeItem: key => state.delete(key)};
assert.deepEqual(R.read(storage), []);
let entries = R.remember([], 'https://team.larksuite.com/sheets/exampleSpreadsheet123?sheet=abc#fragment', '문서 A');
assert.equal(entries[0].source, 'https://team.larksuite.com/sheets/exampleSpreadsheet123');
entries = R.remember(entries, 'otherSpreadsheet456', '문서 B');
entries = R.remember(entries, 'exampleSpreadsheet123', '수정된 제목');
assert.equal(entries.length, 2); assert.equal(entries[0].title, '수정된 제목');
entries = R.remember(entries, 'https://team.larksuite.com/wiki/exampleWikiNode123', '위키 시트');
assert.equal(entries[0].title, '위키 시트');
assert.equal(R.write(storage, entries), true);
assert.deepEqual(R.read(storage), entries);
for (let i = 0; i < 20; i++) entries = R.remember(entries, 'SpreadsheetToken' + i, '문서 ' + i);
assert.equal(entries.length, 5); assert.equal(entries[0].title, '문서 19');
assert.equal(R.normalizeSource('https://evil.com/sheets/exampleSpreadsheet123'), null);
state.set(R.KEY, '{broken'); assert.deepEqual(R.read(storage), []);
state.set(R.KEY, '[{"source":"javascript:alert(1)","title":"bad"}]'); assert.deepEqual(R.read(storage), []);
assert.deepEqual(R.read(null), []); assert.equal(R.write(null, entries), false);
R.write(storage, entries); R.clear(storage); assert.deepEqual(R.read(storage), []);
console.log('PASS: persistence, deduplication, updated names, limit, URL normalization, invalid storage, clearing');
