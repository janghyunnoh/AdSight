const assert = require('node:assert/strict');
const D = require('../app/static/data-utils.js');
assert.equal(D.number('1,234.5'), 1234.5);
for (const value of ['', null, true, '3%', '₩100', '2026-10-01', '12,34']) assert.equal(D.number(value), null);
const rows = [{values: ['10'], id: 1}, {values: [null], id: 2}, {values: ['2'], id: 3}, {values: ['2'], id: 4}];
assert.deepEqual(D.sortRows(rows, 0, 1).map(row => row.id), [3, 4, 1, 2]);
assert.deepEqual(D.sortRows(rows, 0, -1).map(row => row.id), [1, 3, 4, 2]);
assert.deepEqual(D.sortRows(rows, 0, 0).map(row => row.id), [1, 2, 3, 4]);
assert.deepEqual(rows.map(row => row.id), [1, 2, 3, 4]);
const dates = ['10/1/2026', '1/1/2027', '2/1/2026'].map(value => ({values: [value]}));
assert.deepEqual(D.sortRows(dates, 0, 1).map(row => row.values[0]), ['2/1/2026', '10/1/2026', '1/1/2027']);
const input = [['A', '1,000'], ['A', 0], ['A', null], ['B', -50], ['B', 'invalid'], ['__proto__', 4]];
const sum = D.aggregate(input, 0, 1, 'sum');
assert.equal(sum[0].value, 1000); assert.equal(sum[0].rows, 3); assert.equal(sum[0].valid, 2);
assert.equal(sum[1].value, -50); assert.equal(sum[2].key, '__proto__');
assert.equal(D.aggregate(input, 0, 1, 'mean')[0].value, 500);
assert.equal(D.aggregate(input, 0, 1, 'min')[0].value, 0);
assert.equal(D.aggregate(input, 0, 1, 'max')[0].value, 1000);
assert.equal(D.aggregate([['A', null]], 0, 1, 'sum')[0].value, null);
assert.deepEqual(D.aggregate([], 0, 1, 'sum'), []);
console.log('PASS: numeric parsing, stable numeric/date sorting, blanks, original order, aggregation, negative/zero values');
const overview = D.profile(['Date', 'Campaign', 'Spend', '회사명'], [['10/1/2026', 'A', '100', '회사 A'], ['10/2/2026', 'A', '200', '회사 B']]);
assert.equal(overview.dateColumn, 0);
assert.equal(overview.groupColumn, 3);
assert.deepEqual(overview.numeric, [2]);
const generic = D.profile(['날짜', '플랫폼', '값'], [['2026-01-01', 'Meta', 0], ['2026-01-02', 'Meta', -1], ['2026-01-03', 'Google', 12]]);
assert.equal(generic.groupColumn, 1);
assert.equal(D.profile(['내용'], [['텍스트']]).dateColumn, -1);
assert.deepEqual(D.profile(['숫자'], [['10'], ['invalid']]).numeric, []);
assert.equal(D.date('2026-02-30'), null);
assert.equal(D.date('2026-02-28'), Date.UTC(2026, 1, 28));
console.log('PASS: overview defaults, company selection, date detection, mixed values, invalid dates');
const comparisons = D.compareGroups([['A', 100, 10], ['A', 200, 20], ['B', 0, null]], 0, [{index: 1, operation: 'sum'}, {index: 2, operation: 'mean'}]);
assert.deepEqual(comparisons, [{key: 'A', values: [300, 15]}, {key: 'B', values: [0, null]}]);
assert.deepEqual(D.compareGroups([], 0, [{index: 1, operation: 'sum'}]), []);
assert.deepEqual(D.compareGroups([['A', 1]], 0, []), [{key: 'A', values: []}]);
const ranked = D.sortRows(comparisons.map(item => ({values: [item.key, ...item.values]})), 1, -1);
assert.deepEqual(ranked.map(item => item.values[0]), ['A', 'B']);
console.log('PASS: multiple comparison metrics, per-metric operations, null/zero handling, comparison sorting');
const seriesRows = [['2026-10-01','A',10], ['2026-10-01','A',20], ['2026-10-02','B',0], ['2026-10-03','A',-5], ['invalid','A',99]];
const series = D.timeSeries(seriesRows, 0, 1, 2, 'sum', ['A','B']);
assert.equal(series.length, 2);
assert.deepEqual(series[0].points.map(p=>p.value), [30,null,-5]);
assert.deepEqual(series[1].points.map(p=>p.value), [null,0,null]);
assert.deepEqual(D.timeSeries(seriesRows,0,1,2,'mean',['A'])[0].points.map(p=>p.value), [15,null,-5]);
assert.deepEqual(D.timeSeries([],0,1,2,'sum',['A'])[0].points, []);
console.log('PASS: multi-target date alignment, same-date aggregation, missing values, zero and negative values');
const scale=D.niceScale([132347,287654]);
assert.equal(scale.low,0); assert.ok(scale.high>=287654);
const spacing=scale.ticks[1]-scale.ticks[0];
assert.ok(scale.ticks.every((value,index)=>index===0||Math.abs(value-scale.ticks[index-1]-spacing)<1e-6));
assert.ok(D.niceScale([-70,30]).low<=-70);
assert.ok(D.niceScale([0,0]).high>0);
assert.equal(D.displayNumber(150000,300000),'15만');
assert.equal(D.displayNumber(150000000,300000000),'1.5억');
assert.equal(D.displayNumber(0,300000),'0');
assert.equal(D.displayNumber(null,300000),'—');
assert.equal(D.displayNumber(.00005,0),'0.00005');
console.log('PASS: readable evenly spaced axis ticks, shared units, negatives, zero, tiny values');
assert.deepEqual(D.dateTicks([1,2,3,4,5,6,7]),[1,3,5,7]);
assert.deepEqual(D.dateTicks([1,2]),[1,2]);
assert.deepEqual(D.dateTicks([]),[]);
assert.deepEqual(D.dateTicks([3,1,1,2]),[1,2,3]);
console.log('PASS: four evenly distributed date labels and short/empty date ranges');
